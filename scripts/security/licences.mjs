// P11 A3: licences of the RUNTIME dependency closure (production dependencies and everything they pull in),
// read from node_modules/*/package.json. `node scripts/security/licences.mjs [--write]` prints a table and,
// with --write, docs/reports/licences.md. Exit code 1 if a runtime package has no licence field or one that is
// not on the permissive list (review it by hand before shipping).
import { existsSync, readFileSync, writeFileSync } from 'node:fs';
import { join } from 'node:path';

const ROOT = join(import.meta.dirname, '..', '..');
const pkg = JSON.parse(readFileSync(join(ROOT, 'package.json'), 'utf8'));
// Reviewed by hand: not on the permissive list but acceptable, with the reason.
const REVIEWED = {
  gsap: 'GSAP "Standard no-charge licence" (gsap.com/standard-license): proprietary but free for commercial use, including ScrollTrigger and SplitText since 2025; it only forbids building a product that competes with Webflow and GSAP visual animation tools. Used here as a library inside a portfolio, which is allowed.',
};
const PERMISSIVE = /^(?:MIT|ISC|BSD-2-Clause|BSD-3-Clause|Apache-2\.0|0BSD|BlueOak-1\.0\.0|CC0-1\.0|OFL-1\.1|Unlicense|MIT-0|Python-2\.0)$/;

function read(name) {
  const file = join(ROOT, 'node_modules', name, 'package.json');
  return existsSync(file) ? JSON.parse(readFileSync(file, 'utf8')) : null;
}
const seen = new Map();
(function walk(name) {
  if (seen.has(name)) return;
  const p = read(name);
  if (!p) return;
  seen.set(name, p);
  for (const dep of Object.keys(p.dependencies ?? {})) walk(dep);
  for (const dep of Object.keys(p.optionalDependencies ?? {})) walk(dep);
})('');
for (const name of Object.keys(pkg.dependencies)) (function walk(n) {
  if (seen.has(n)) return;
  const p = read(n);
  if (!p) return;
  seen.set(n, p);
  for (const dep of [...Object.keys(p.dependencies ?? {}), ...Object.keys(p.optionalDependencies ?? {})]) walk(dep);
})(name);

const licenceOf = (p) => (typeof p.license === 'string' ? p.license : p.license?.type ?? (Array.isArray(p.licenses) ? p.licenses.map((l) => l.type).join(' OR ') : ''));
const rows = [...seen.entries()].filter(([n]) => n).map(([n, p]) => ({ name: n, version: p.version, licence: licenceOf(p) || '(none declared)', direct: n in pkg.dependencies })).sort((a, b) => a.name.localeCompare(b.name));
const bad = rows.filter((r) => !REVIEWED[r.name] && !PERMISSIVE.test(r.licence.replace(/[()]/g, '').split(/ OR /)[0].trim()));
const byLicence = {};
for (const r of rows) byLicence[r.licence] = (byLicence[r.licence] ?? 0) + 1;

const lines = [
  '# Licences of the runtime dependencies',
  '',
  `Generated by \`node scripts/security/licences.mjs --write\` on ${new Date().toISOString().slice(0, 10)} (UTC) from \`node_modules\` (the production dependency closure: ${rows.length} packages, ${rows.filter((r) => r.direct).length} direct). Dev tools (vite, vitest, tailwind, lighthouse, playwright-core) are not shipped to visitors and are not listed.`,
  '',
  `**Result:** ${bad.length ? `${bad.length} package(s) need a manual look: ${bad.map((b) => `${b.name} (${b.licence})`).join(', ')}` : 'every runtime package has a permissive licence (MIT, MIT-0, ISC, BSD, Apache-2.0 or OFL-1.1) except GSAP, which has a free-for-commercial-use proprietary licence reviewed by hand below; nothing copyleft, nothing without a licence.'}`,
  '',
  ...(Object.keys(REVIEWED).some((n) => seen.has(n)) ? ['**Reviewed by hand:**', '', ...Object.entries(REVIEWED).filter(([n]) => seen.has(n)).map(([n, why]) => `- **${n}**: ${why}`), ''] : []),
  `Summary: ${Object.entries(byLicence).map(([l, n]) => `${l} ×${n}`).join(', ')}.`,
  '',
  '| Package | Version | Licence | Direct |',
  '|---|---|---|---|',
  ...rows.map((r) => `| ${r.name} | ${r.version} | ${r.licence} | ${r.direct ? 'yes' : ''} |`),
];
lines.push(
  '',
  '## Third-party assets (fonts, audio, textures, models, images)',
  '',
  '| Asset | Origin | Licence / proof |',
  '|---|---|---|',
  '| Fonts: Courier Prime, Rokkitt, Source Serif 4, Ultra | npm `@fontsource/*`, self-hosted (no Google Fonts request) | SIL OFL 1.1 (Ultra: Apache-2.0); listed above |',
  '| Site audio (wind, sea, crickets, footsteps, music, whistle, harmonica) | Synthesised by the code in `src/explore/` (Web Audio) | Original, nothing to license (`docs/DESIGN.md` §11) |',
  '| Promo film score and sound effects | Generated by `scripts/promo/` (no samples, no stock audio) | Original; `aftereffects/LICENCE-AUDIO.md` |',
  '| Paper grain texture `public/textures/grain.svg` | An SVG `feTurbulence` filter written for this site | Original |',
  '| 3D models `public/models/*.glb` (town, avatar, horse, train, oars) | Built by Umer and Claude with Blender Python scripts in `blender/` (no AI generators, no imported third-party models, no base meshes) | Original (`docs/PLAN.md` P8, decision record 9-Nov-2026) |',
  '| Draco decoder `public/draco/*` | Google Draco (copied from the `three` package) | Apache-2.0 |',
  '| Project covers, headshots, certificates, promo video and poster | Own work of Umer: screenshots and scans; illustrated covers generated by `scripts/content/illustrated-covers.py` | Own work; a certificate scan is shown with the issuer name only as proof of the credential |',
  '',
  'Not verified by a tool: image provenance is a statement by the owner, not something a scanner can prove.',
);
console.log(lines.slice(0, 8).join('\n'));
if (process.argv.includes('--write')) {
  writeFileSync(join(ROOT, 'docs', 'reports', 'licences.md'), lines.join('\n') + '\n');
  console.log('wrote docs/reports/licences.md');
}
process.exitCode = bad.length ? 1 : 0;
