// P7: the public project slugs (drafts excluded) in their built-in order, as a small committed module the admin
// API can import (a Vercel function does not read /content at run time). `node scripts/content/slugs.mjs` rewrites
// src/shared/project-slugs.js; a test fails when it no longer matches /content, so it cannot drift.
import { writeFileSync } from 'node:fs';
import { join } from 'node:path';
import { loadContent } from './load.mjs';

const ROOT = join(import.meta.dirname, '..', '..');

export function publicProjects(root = ROOT) {
  return loadContent(root).content.projects.filter((p) => !p.draft).map((p) => ({ slug: p.slug, title: p.title }));
}

export function render(projects) {
  return [
    '// GENERATED by `node scripts/content/slugs.mjs` from /content/projects (drafts excluded). Do not edit by hand:',
    '// tests/security/p7-admin.test.js fails when this list and /content disagree.',
    '// The admin API validates a saved project order against these slugs; the order here is the built-in one.',
    `export const PROJECTS = ${JSON.stringify(projects, null, 2)};`,
    '',
    'export const PROJECT_SLUGS = PROJECTS.map((p) => p.slug);',
    '',
  ].join('\n');
}

if (process.argv[1]?.endsWith('slugs.mjs')) {
  const projects = publicProjects();
  writeFileSync(join(ROOT, 'src', 'shared', 'project-slugs.js'), render(projects));
  console.log(`src/shared/project-slugs.js: ${projects.length} public projects`);
}
